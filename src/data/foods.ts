/** 预置食物库 */
export const PRESET_FOODS: FoodItem[] = RAW.map(
  ([name, category, kcal, protein, carb, fat, fiber, sodium, serving], index) => ({
    id: `fd-${String(index + 1).padStart(3, '0')}`,
    name,
    category,
    kcal,
    protein,
    carb,
    fat,
    fiber,
    sodium,
    serving
  })
);

/**
 * 预置食物实拍图：随饮食分包打包，路径 foods-photo/{食物 id}.jpg
 * 图片来自用户提供的食物图表（统一白底单品图）。
 * 旧版食物库的 id（food-xxx）已经没有图片，返回 null 走分类图标。
 */
export function foodPhoto(food: FoodItem): string | null {
  if (food.isCustom) return null;
  if (!food.id.startsWith('fd-')) return null;
  return cloudFile(`foods-photo/${food.id}.jpg`);
}

/** 分类兜底图标（Emoji 图，自定义食物没拍照时用） */
const CATEGORY_ICON: Record<FoodCategory, string> = {
  staple: '1f35a',
  meat: '1f357',
  dairy: '1f95b',
  veg: '1f966',
  fruit: '1f34e',
  nut: '1f95c',
  drink: '1f964',
  supplement: '1f4aa',
  other: '1f9c2'
};

export function foodIcon(food: FoodItem): string {
  return `/assets/foods/${CATEGORY_ICON[food.category]}.png`;
}

/** 按 id 取食物（预置 + 自定义） */
export function findFood(id: string, custom: FoodItem[]): FoodItem | undefined {
  return custom.find((item) => item.id === id) || PRESET_FOODS.find((item) => item.id === id);
}
